# Voidaan vapaasti kommentoida koodia
print("hello")

# muuttuja on yksinkertaisesti tallennuspaikka, johon voit tallentaa yhden arvon
age = 30
print(age)

# Voit myöhemmin koodissa muuttaa muuttujan arvoa, esimerkiksi
age = 40
print(age)

temperature = 13.5 # Desimaalierotin on aina piste
print(temperature)

# jos käytätte muuttujan nimenä kahta sanaa niin pythonissa on tapana käyttää alaviivaa
# välissä (tyhjää ei voi olla muuttujan nimessä)

first_name = "Samu"
last_name = "Koponen"

#Jos printataan molemmat tiedot, niin esim. näin

print(first_name + " " + last_name)

# Jos halutaan väli nimien välille: laitetaan "välilyönti"

print("nimesi on " + first_name + " " + last_name)

# + asemasta voi myös käyttää pilkkua merkkijonojen yhdistämiseen ja silloin välilyönti
# lisätään sanojen väliin automaattisesti

print("nimi on",first_name, last_name)

